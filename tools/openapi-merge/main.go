// Command openapi-merge merges internal/api/openapi/*.yaml fragments into internal/api/openapi.yaml.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"

	"gopkg.in/yaml.v3"
)

func main() {
	dir, out := "internal/api/openapi", "internal/api/openapi.yaml"
	if len(os.Args) == 3 {
		dir, out = os.Args[1], os.Args[2]
	}
	files, _ := filepath.Glob(filepath.Join(dir, "*.yaml"))
	sort.Strings(files)
	paths, schemas := map[string]any{}, map[string]any{}
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			fail(err)
		}
		var doc struct {
			Paths      map[string]any `yaml:"paths"`
			Components struct {
				Schemas map[string]any `yaml:"schemas"`
			} `yaml:"components"`
		}
		if err := yaml.Unmarshal(b, &doc); err != nil {
			fail(fmt.Errorf("%s: %w", f, err))
		}
		for k, v := range doc.Paths {
			if _, dup := paths[k]; dup {
				fail(fmt.Errorf("%s: duplicate path %s", f, k))
			}
			paths[k] = v
		}
		for k, v := range doc.Components.Schemas {
			schemas[k] = v
		}
	}
	spec := map[string]any{
		"openapi": "3.1.0",
		"info": map[string]any{"title": "ServerKeeper API", "version": "1.0",
			"description": "REST API (/api/v1). Auth: Bearer API token (scopes read, ssh:write, harden:write, admin) " +
				"or session cookie + X-CSRF-Token header."},
		"servers": []any{map[string]any{"url": "/api/v1"}},
		"paths":   paths,
		"components": map[string]any{
			"schemas": schemas,
			"securitySchemes": map[string]any{
				"bearer":  map[string]any{"type": "http", "scheme": "bearer"},
				"session": map[string]any{"type": "apiKey", "in": "cookie", "name": "sk_session"},
			},
		},
		"security": []any{map[string]any{"bearer": []any{}}, map[string]any{"session": []any{}}},
	}
	b, err := yaml.Marshal(spec)
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(out, append([]byte("# generated by tools/openapi-merge from internal/api/openapi/*.yaml; do not edit\n"), b...), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("%s: %d paths, %d schemas\n", out, len(paths), len(schemas))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
